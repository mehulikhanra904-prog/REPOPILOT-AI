function CodeExplorer({ analysis, selectedPath, selectedFile, onSelectFile, repoUrl, onError }) {
  const files = useMemo(() => analysis.tree.filter((item) => item.type === "file"), [analysis.tree]);
  const [search, setSearch] = useState("");
  const [explanation, setExplanation] = useState(null);
  const [explaining, setExplaining] = useState(false);
  const filteredFiles = files.filter((file) => file.path.toLowerCase().includes(search.toLowerCase())).slice(0, 250);
  const activeFile = selectedFile || analysis.previews?.find((file) => file.path === selectedPath);

  useEffect(() => {
    if (!selectedPath && files[0]) onSelectFile(files[0].path);
  }, [selectedPath, files]);

  async function explain() {
    if (!activeFile) return;
    setExplaining(true);
    setExplanation(null);
    try {
      const result = await apiRequest("/api/explain", { method: "POST", body: JSON.stringify({ repo_url: repoUrl, path: activeFile.path }) });
      setExplanation(result);
    } catch (error) {
      onError(error.message);
    } finally {
      setExplaining(false);
    }
  }

  return <div className="explorer-layout">
    <section className="panel explorer-sidebar">
      <div className="explorer-title"><div><div className="panel-eyebrow">Source browser</div><h2>Repository files</h2></div><span className="file-count">{files.length}</span></div>
      <div className="file-search"><Search size={15} /><input value={search} onChange={(event) => setSearch(event.target.value)} placeholder="Filter files..." /></div>
      <div className="file-tree">{filteredFiles.length ? filteredFiles.map((file) => <button className={`file-row ${selectedPath === file.path ? "active" : ""}`} key={file.path} onClick={() => { setExplanation(null); onSelectFile(file.path); }}><FileIcon path={file.path} /><span>{file.path}</span><ChevronRight size={13} /></button>) : <EmptyPanel text="No matching source files." />}</div>
      {files.length > 250 && <div className="tree-note">Showing first 250 matches.</div>}
    </section>
    <section className="panel code-panel">
      {activeFile ? <>
        <div className="code-header"><div className="code-file-title"><FileIcon path={activeFile.path} /><div><strong>{activeFile.path}</strong><span>{activeFile.language || "Text"} · {formatNumber(activeFile.size)} bytes</span></div></div><button className="ai-button" onClick={explain} disabled={explaining}>{explaining ? <LoaderCircle size={15} className="spin" /> : <Sparkles size={15} />}{explaining ? "Thinking" : "Explain with AI"}</button></div>
        {explanation && <div className="explanation-card"><div className="explanation-head"><div><Sparkles size={15} /><strong>RepoPilot explanation</strong><span>{explanation.powered_by}</span></div><button onClick={() => setExplanation(null)}><X size={15} /></button></div><AnswerText text={explanation.answer} /></div>}
        <div className="source-view"><pre>{(activeFile.content || "Loading file...").split("\n").map((line, index) => <code key={index}><span className="line-number">{String(index + 1).padStart(3, " ")}</span><span>{line || " "}</span>{"\n"}</code>)}</pre></div>
      </> : <div className="code-empty"><LoaderCircle size={25} className="spin" /><p>Loading a source file...</p></div>}
    </section>
  </div>;
}

function FileIcon({ path }) {
  const isFolder = path.endsWith("/");
  if (isFolder) return <Folder size={15} />;
  if (path.endsWith(".json")) return <Braces size={15} />;
  return <FileCode2 size={15} />;
}

function Insights({ analysis, onSelectFile }) {
  const issues = analysis.quality.issues;
  const [filter, setFilter] = useState("all");
  const filteredIssues = filter === "all" ? issues : issues.filter((issue) => issue.severity === filter);
  const filterOptions = [{ id: "all", label: "All", count: issues.length }, ...["high", "medium", "low"].map((severity) => ({ id: severity, label: severity[0].toUpperCase() + severity.slice(1), count: issues.filter((issue) => issue.severity === severity).length }))];
  return <div className="insights-layout"><div className="insights-intro"><div><div className="panel-eyebrow">Explainable review</div><h2>Quality insights</h2><p>Signals are generated from the repository tree and a sample of source files. They are prompts for review, not a replacement for tests or a full security audit.</p></div><div className="insight-score"><strong>{analysis.quality.score}</strong><span>health score</span></div></div><div className="insight-toolbar"><div className="filter-label">Filter signals</div>{filterOptions.map((option) => <button key={option.id} className={filter === option.id ? "active" : ""} onClick={() => setFilter(option.id)}>{option.label}<span>{option.count}</span></button>)}</div><div className="insight-grid">{filteredIssues.length ? filteredIssues.map((issue, index) => <article className="panel insight-card" key={`${issue.title}-${index}`}><div className={`insight-severity ${issue.severity}`}><span className="severity-dot" />{issue.severity} priority</div><h3>{issue.title}</h3><p>{issue.description}</p><div className="insight-footer">{issue.file ? <button onClick={() => onSelectFile(issue.file)}><FileCode2 size={14} />{issue.file}</button> : <span><Layers3 size={14} /> Repository-wide</span>}<span className="insight-type">static signal</span></div></article>) : <div className="panel no-issues"><div className="success-icon"><Check size={22} /></div><h3>{issues.length ? `No ${filter} priority signals` : "Clean first pass"}</h3><p>{issues.length ? "Try another filter to see the other repository signals." : "No high-confidence signals were found in the available source sample."}</p></div>}</div></div>;
}

function AskRepo({ analysis, repoUrl, selectedPath }) {
  const [question, setQuestion] = useState("");
  const [messages, setMessages] = useState([{ role: "assistant", text: `I’ve mapped **${analysis.repository.full_name}**. Ask me about the architecture, a potential bug, the stack, or a specific file.`, poweredBy: "ready" }]);
  const [asking, setAsking] = useState(false);

  async function submitQuestion(event) {
    event?.preventDefault();
    const value = question.trim();
    if (!value || asking) return;
    setQuestion("");
    setMessages((current) => [...current, { role: "user", text: value }]);
    setAsking(true);
    try {
      const result = await apiRequest("/api/ask", { method: "POST", body: JSON.stringify({ repo_url: repoUrl, question: value, selected_path: selectedPath || null }) });
      setMessages((current) => [...current, { role: "assistant", text: result.answer, poweredBy: result.powered_by }]);
    } catch (error) {
      setMessages((current) => [...current, { role: "assistant", text: error.message, poweredBy: "error" }]);
    } finally {
      setAsking(false);
    }
  }

  const prompts = ["What is the architecture?", "Find potential bugs", "What should I improve first?"];
  return <div className="ask-layout"><section className="ask-main panel"><div className="ask-heading"><div className="ai-orb"><Sparkles size={20} /></div><div><div className="panel-eyebrow">Contextual code chat</div><h2>Ask about this repository</h2><p>Answers use the repository map, quality signals, and selected source file context.</p></div></div><div className="chat-thread">{messages.map((message, index) => <div className={`chat-message ${message.role}`} key={`${message.role}-${index}`}><div className="chat-avatar">{message.role === "assistant" ? <Sparkles size={14} /> : <span>you</span>}</div><div className="chat-bubble"><AnswerText text={message.text} />{message.poweredBy && <span className="powered-by">{message.poweredBy === "ready" ? "RepoPilot ready" : `Powered by ${message.poweredBy}`}</span>}</div></div>)}{asking && <div className="chat-message assistant"><div className="chat-avatar"><Sparkles size={14} /></div><div className="chat-bubble typing"><span /><span /><span /></div></div>}</div><form className="ask-composer" onSubmit={submitQuestion}><textarea value={question} onChange={(event) => setQuestion(event.target.value)} placeholder="Ask anything about the codebase..." rows="2" /><button className="send-button" type="submit" disabled={!question.trim() || asking}>{asking ? <LoaderCircle size={17} className="spin" /> : <Send size={17} />}</button></form><div className="prompt-row">{prompts.map((prompt) => <button key={prompt} onClick={() => setQuestion(prompt)}>{prompt}</button>)}</div></section><aside className="ask-side"><div className="panel context-card"><div className="panel-eyebrow">Active context</div><h3><Github size={16} />{analysis.repository.full_name}</h3><div className="context-stat"><span>Primary language</span><strong>{analysis.languages[0]?.name || "Unknown"}</strong></div><div className="context-stat"><span>Files mapped</span><strong>{formatNumber(analysis.file_count)}</strong></div><div className="context-stat"><span>Quality score</span><strong>{analysis.quality.score}/100</strong></div></div><div className="panel ask-tip"><Lightbulb size={17} /><div><strong>Get better answers</strong><p>Select a file in Code Explorer first, then return here to include it in your question context.</p></div></div></aside></div>;
}

function AnswerText({ text }) {
  const lines = String(text || "").split("\n");
  return <div className="answer-copy">{lines.map((line, lineIndex) => <span className="answer-line" key={lineIndex}>{line.split(/(\*\*[^*]+\*\*|`[^`]+`)/g).map((part, partIndex) => part.startsWith("**") && part.endsWith("**") ? <strong key={partIndex}>{part.slice(2, -2)}</strong> : part.startsWith("`") && part.endsWith("`") ? <code key={partIndex}>{part.slice(1, -1)}</code> : <span key={partIndex}>{part}</span>)}</span>)}</div>;
}

