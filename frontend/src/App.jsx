const API_BASE = import.meta.env.VITE_API_URL || "";

async function apiRequest(path, options = {}) {
  const response = await fetch(`${API_BASE}${path}`, {
    headers: { "Content-Type": "application/json", ...(options.headers || {}) },
    ...options,
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(payload.detail || "Something went wrong. Please try again.");
  return payload;
}

function formatNumber(value = 0) {
  return new Intl.NumberFormat("en", { notation: value > 9999 ? "compact" : "standard" }).format(value);
}

function formatDate(value) {
  if (!value) return "—";
  return new Intl.DateTimeFormat("en", { month: "short", day: "numeric", year: "numeric" }).format(new Date(value));
}

function exportMarkdownReport(analysis) {
  const { repository, languages = [], architecture = {}, quality = {}, activity = {} } = analysis;
  const lines = [
    `# RepoPilot AI report — ${repository.full_name}`,
    "",
    repository.description,
    "",
    `- Repository: ${repository.html_url}`,
    `- Default branch: ${repository.default_branch}`,
    `- Stars: ${repository.stars}`,
    `- Forks: ${repository.forks}`,
    `- Files indexed: ${analysis.file_count}`,
    `- Quality score: ${quality.score}/100 (Grade ${quality.grade})`,
    `- Last push: ${formatDate(activity.last_push || repository.pushed_at)}`,
    "",
    "## Architecture signals",
    "",
    architecture.summary || "No architecture summary was returned.",
    "",
    `- Stacks: ${(architecture.stacks || []).join(", ") || "Not detected"}`,
    `- Entry points: ${(architecture.entrypoints || []).join(", ") || "Not detected"}`,
    `- Test-related files: ${architecture.test_file_count || 0}`,
    `- CI workflows: ${architecture.workflow_count || 0}`,
    "",
    "## Languages",
    "",
    ...languages.map((language) => `- ${language.name}: ${language.percentage}%`),
    "",
    "## Quality insights",
    "",
    ...(quality.issues?.length ? quality.issues.map((issue) => `- **${issue.severity}** — ${issue.title}${issue.file ? ` (${issue.file})` : ""}: ${issue.description}`) : ["No high-confidence signals found."]),
    "",
    "## Recent commits",
    "",
    ...(activity.recent_commits?.length ? activity.recent_commits.map((commit) => `- ${commit.message} — ${commit.author} (${commit.sha})`) : ["No recent commit activity returned."]),
    "",
    "Generated by RepoPilot AI.",
  ];
  const blob = new Blob([lines.join("\n")], { type: "text/markdown;charset=utf-8" });
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = `${repository.full_name.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "")}-repilot-report.md`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(link.href);
}

