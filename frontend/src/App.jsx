function App() {
  const [repoUrl, setRepoUrl] = useState("");
  const [analysis, setAnalysis] = useState(null);
  const [activeView, setActiveView] = useState("overview");
  const [selectedPath, setSelectedPath] = useState("");
  const [selectedFile, setSelectedFile] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [mobileNav, setMobileNav] = useState(false);
  const fileRequestId = useRef(0);
  const [history, setHistory] = useState(() => {
    try {
      return JSON.parse(localStorage.getItem("repilot-history") || "[]");
    } catch {
      return [];
    }
  });

  useEffect(() => {
    apiRequest("/api/health").catch(() => undefined);
  }, []);

  async function analyzeRepository(value = repoUrl, forceRefresh = false) {
    const trimmed = value.trim();
    if (!trimmed) {
      setError("Paste a GitHub repository URL to start the analysis.");
      return;
    }
    setLoading(true);
    setError("");
    try {
      const result = await apiRequest("/api/analyze", { method: "POST", body: JSON.stringify({ repo_url: trimmed, force_refresh: forceRefresh }) });
      setAnalysis(result);
      setRepoUrl(trimmed);
      setSelectedPath("");
      setSelectedFile(null);
      setActiveView("overview");
      setMobileNav(false);
      const nextHistory = [
        { url: trimmed, name: result.repository.full_name, analyzedAt: Date.now() },
        ...history.filter((item) => item.url !== trimmed),
      ].slice(0, 4);
      setHistory(nextHistory);
      localStorage.setItem("repilot-history", JSON.stringify(nextHistory));
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setLoading(false);
    }
  }

  async function selectFile(path) {
    if (!path || !analysis) return;
    const requestId = ++fileRequestId.current;
    setSelectedPath(path);
    setSelectedFile(null);
    try {
      const file = await apiRequest("/api/file", {
        method: "POST",
        body: JSON.stringify({ repo_url: repoUrl, path }),
      });
      if (requestId === fileRequestId.current) setSelectedFile(file);
    } catch (requestError) {
      setError(requestError.message);
    }
  }

  function openView(view) {
    if (!analysis && view !== "overview") return;
    setActiveView(view);
    setMobileNav(false);
  }

  const navItems = [
    { id: "overview", label: "Overview", icon: Layers3 },
    { id: "code", label: "Code Explorer", icon: Code2 },
    { id: "insights", label: "Quality Insights", icon: ShieldCheck, badge: analysis?.quality?.issues?.length },
    { id: "ask", label: "Ask RepoPilot", icon: MessageSquare, accent: true },
  ];

  return (
    <div className="app-shell">
      {mobileNav && <button className="mobile-scrim" aria-label="Close navigation" onClick={() => setMobileNav(false)} />}
      <aside className={`sidebar ${mobileNav ? "sidebar-open" : ""}`}>
        <div className="brand-lockup">
          <div className="brand-mark"><Sparkles size={18} /></div>
          <div><strong>RepoPilot</strong><span>AI</span></div>
        </div>
        <div className="sidebar-label">Workspace</div>
        <nav className="side-nav" aria-label="Main navigation">
          {navItems.map(({ id, label, icon: Icon, badge, accent }) => (
            <button
              className={`side-nav-item ${activeView === id ? "active" : ""} ${accent ? "accent" : ""}`}
              key={id}
              onClick={() => openView(id)}
            >
              <Icon size={17} strokeWidth={1.8} />
              <span>{label}</span>
              {badge > 0 && <em>{badge}</em>}
            </button>
          ))}
        </nav>
        <div className="sidebar-label recent-label">Recent scans</div>
        <div className="recent-list">
          {history.length ? history.map((item) => (
            <button className="recent-item" key={item.url} onClick={() => analyzeRepository(item.url)}>
              <Github size={14} />
              <span>{item.name?.split("/").pop() || item.url}</span>
            </button>
          )) : <p className="muted small-copy">Your analyzed repositories will appear here.</p>}
        </div>
        <div className="sidebar-bottom">
          <div className="engine-status"><span className="status-dot" /> Analysis engine online</div>
          <p>GitHub metadata and static signals work without an AI key.</p>
        </div>
      </aside>

      <main className="workspace">
        <header className="topbar">
          <button className="mobile-menu" onClick={() => setMobileNav(true)} aria-label="Open navigation"><PanelLeft size={19} /></button>
          <div className="breadcrumb"><span>Workspace</span><ChevronRight size={14} /><strong>{analysis ? analysis.repository.name : "New analysis"}</strong></div>
          <div className="topbar-actions">
            <div className="secure-pill"><span className="status-dot" /> Secure backend</div>
            {analysis && <a className="icon-link" href={analysis.repository.html_url} target="_blank" rel="noreferrer" title="Open on GitHub"><ExternalLink size={17} /></a>}
            {analysis && <button className="ghost-button compact" onClick={() => analyzeRepository(repoUrl, true)} disabled={loading}><RefreshCw size={15} className={loading ? "spin" : ""} /> Rescan</button>}
          </div>
        </header>

        <div className="content-area">
          {!analysis ? (
            <WelcomeScreen repoUrl={repoUrl} setRepoUrl={setRepoUrl} onAnalyze={analyzeRepository} loading={loading} error={error} />
          ) : (
            <>
              <AnalysisHeader analysis={analysis} activeView={activeView} onViewChange={openView} />
              {error && <ErrorBanner message={error} onDismiss={() => setError("")} />}
              {activeView === "overview" && <Overview analysis={analysis} onViewChange={openView} onSelectFile={selectFile} />}
              {activeView === "code" && <CodeExplorer analysis={analysis} selectedPath={selectedPath} selectedFile={selectedFile} onSelectFile={selectFile} repoUrl={repoUrl} onError={setError} />}
              {activeView === "insights" && <Insights analysis={analysis} onSelectFile={(path) => { setActiveView("code"); selectFile(path); }} />}
              {activeView === "ask" && <AskRepo analysis={analysis} repoUrl={repoUrl} selectedPath={selectedPath} />}
            </>
          )}
        </div>
      </main>
    </div>
  );
}

